const b={...a,id:'B',manifest:{...m,version:'v2'},metric:{value:1,unknown:0}};
assert(N.comparison(a,b).ok);
assert(!N.comparison(a,{...b,manifest:{...m,object:'another-object'}}).ok);
assert(!N.comparison(a,{...b,manifest:{...m,bindings:['EX@2']}}).ok);
assert(!N.comparison(a,a).ok);
assert(!N.comparison(a,{...b,metric:{value:1,unknown:1}}).ok);
